// 431-10 (PXH-AGENT-01/02 · D-14..D-20): the generated knowledge guide and the root pointer,
// driven through the real `init` command against real temporary directories.
import {
  existsSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  unlinkSync,
  writeFileSync,
} from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { stripVTControlCharacters } from 'node:util'

import { AGENT_QA_TOOL_PROJECTIONS } from '@vostride/agent-qa-mcp'
import { Command } from 'commander'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'

import { INIT_AGENT_INSTRUCTIONS_VERB } from '../capability-catalog/manifest.js'
import { createInitCommand, type InitCommandHooks } from '../commands/init.js'
import {
  AGENT_QUESTION_MAP,
  KNOWLEDGE_SKILL_NAME,
  WRITE_AGENT_INSTRUCTIONS_FLAG,
  buildAgentInstructionPointer,
  buildKnowledgeAgentGuide,
} from '../commands/knowledge-guide.js'
import { createKnowledgeCommand } from '../commands/knowledge.js'
import { AGENT_QA_INIT_MARKDOWN_BLOCK, renderManagedBlock } from '../commands/managed-block.js'
import { createProposalsCommand } from '../commands/proposals.js'
import { createRunsCommand } from '../commands/runs.js'
import { createSkillsCommand } from '../commands/skills.js'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '../../../..')
const GUIDE = join('agent-qa-knowledge', 'AGENTS.md')
const roots: string[] = []
let log: ReturnType<typeof vi.spyOn>

function tempProject(): string {
  const root = mkdtempSync(join(tmpdir(), 'agent-qa-431-guide-'))
  roots.push(root)
  return root
}

async function runInit(dir: string, extra: string[] = [], hooks: InitCommandHooks = {}): Promise<void> {
  const parent = new Command()
  const init = createInitCommand(hooks)
  parent.exitOverride()
  init.exitOverride()
  parent.addCommand(init)
  await parent.parseAsync(['node', 'test', 'init', '--dir', dir, '--platform', 'web', '--skip-install', ...extra])
}

function stdout(): string {
  return stripVTControlCharacters(log.mock.calls.map((call) => call.map(String).join(' ')).join('\n'))
}

function pointerBlock(): string {
  return renderManagedBlock({
    descriptor: AGENT_QA_INIT_MARKDOWN_BLOCK,
    body: buildAgentInstructionPointer(),
    target: 'AGENTS.md',
  })
}

function liveCommandPath(cli: string): string {
  const program = new Command()
    .addCommand(createRunsCommand())
    .addCommand(createKnowledgeCommand())
    .addCommand(createProposalsCommand())
    .addCommand(createSkillsCommand())
  const words = cli.split(' ').slice(1)
  const path: string[] = []
  let parent: Command | undefined = program
  for (const word of words) {
    const next: Command | undefined = parent?.commands.find((command) => command.name() === word)
    if (next === undefined) break
    path.push(word)
    parent = next
  }
  return path.join(' ')
}

beforeEach(() => {
  log = vi.spyOn(console, 'log').mockImplementation(() => {})
})

afterEach(() => {
  log.mockRestore()
  for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true })
})

describe('INIT-GUIDE-LIFECYCLE: init generates the thin knowledge guide', () => {
  it('fresh init writes the generated guide into the knowledge root', async () => {
    const dir = tempProject()
    await runInit(dir)

    expect(existsSync(join(dir, GUIDE))).toBe(true)
    expect(readFileSync(join(dir, GUIDE), 'utf8')).toBe(buildKnowledgeAgentGuide())
    const created = stdout().match(/ {2}Created:\n([\s\S]*?)(?:\n {2}(?:Updated|Preserved|Next steps):|$)/)?.[1] ?? ''
    expect(created).toContain(GUIDE)
  })

  it('keeps the guide thin, generated and truthful about the layout', () => {
    const guide = buildKnowledgeAgentGuide()
    const lines = guide.split('\n')
    expect(guide.endsWith('\n')).toBe(true)
    expect(lines.length).toBeGreaterThanOrEqual(30)
    expect(lines.length).toBeLessThanOrEqual(50)
    expect(lines[0]).toMatch(/^# agent-qa knowledge/)
    expect(guide).toContain('Generated by agent-qa init')
    for (const needle of [
      'memory/<product>/bundles/<id>/', 'policies/', 'memory/index/', 'memory/queue/', '.lease', '.epoch', 'SQLite',
      'record.md', 'agent-qa skills', KNOWLEDGE_SKILL_NAME,
    ]) {
      expect(guide, needle).toContain(needle)
    }
    for (const row of AGENT_QUESTION_MAP) {
      expect(guide, row.cli).toContain(row.cli)
      expect(guide, row.mcp).toContain(row.mcp)
    }
    expect(guide).toMatch(/never edit files under agent-qa-knowledge\/ yourself/i)
    expect(lines.filter((line) => /propose/i.test(line))).toHaveLength(1)
  })

  it('answers questions overview first, naming only verbs and tools that exist', () => {
    expect(AGENT_QUESTION_MAP[0]).toMatchObject({ mcp: 'agent_qa_get_run_overview' })
    expect(AGENT_QUESTION_MAP[0]!.cli.startsWith('agent-qa runs overview ')).toBe(true)
    expect(AGENT_QUESTION_MAP.map((row) => row.mcp).sort()).toEqual([
      'agent_qa_diff_knowledge_records',
      'agent_qa_explain_brief',
      'agent_qa_get_run_evidence',
      'agent_qa_get_run_knowledge',
      'agent_qa_get_run_overview',
      'agent_qa_inspect_knowledge_records',
      'agent_qa_list_knowledge_bundles',
      'agent_qa_list_knowledge_gates',
      'agent_qa_list_runs',
      'agent_qa_show_knowledge_record',
    ])
    const tools = new Set(AGENT_QA_TOOL_PROJECTIONS.map((projection) => projection.name))
    for (const row of AGENT_QUESTION_MAP) {
      expect(tools.has(row.mcp), row.mcp).toBe(true)
      expect(row.cli.startsWith('agent-qa '), row.cli).toBe(true)
      expect(liveCommandPath(row.cli).split(' '), row.cli).toHaveLength(2)
    }
    const guide = buildKnowledgeAgentGuide()
    for (const tool of guide.match(/agent_qa_[a-z_]+/g) ?? []) expect(tools.has(tool), tool).toBe(true)
    for (const command of guide.match(/`agent-qa [a-z][a-z -]*/g) ?? []) {
      expect(liveCommandPath(command.slice(1)).length, command).toBeGreaterThan(0)
    }
  })

  it('regenerates the guide under --force while user-owned knowledge files are preserved', async () => {
    const dir = tempProject()
    await runInit(dir)
    writeFileSync(join(dir, GUIDE), 'hand edited\n')
    writeFileSync(join(dir, 'agent-qa-knowledge', 'README.md'), 'my readme\n')
    const outcomes: string[] = []

    await runInit(dir, ['--force'], {
      onComplete: (results) => {
        for (const result of results) outcomes.push(`${result.outcome} ${result.path}`)
      },
    })

    expect(readFileSync(join(dir, GUIDE), 'utf8')).toBe(buildKnowledgeAgentGuide())
    expect(outcomes).toContain(`updated ${join(dir, GUIDE)}`)
    expect(readFileSync(join(dir, 'agent-qa-knowledge', 'README.md'), 'utf8')).toBe('my readme\n')
  })

  it('keeps the already-initialized refusal unchanged and writes no guide', async () => {
    const dir = tempProject()
    await runInit(dir)
    unlinkSync(join(dir, GUIDE))
    log.mockClear()

    await runInit(dir)

    expect(stdout()).toContain(`Project is already initialized at ${dir}. Use --force to rebuild it.`)
    expect(existsSync(join(dir, GUIDE))).toBe(false)
    expect(stdout()).not.toContain(pointerBlock())
    expect(existsSync(join(dir, 'AGENTS.md'))).toBe(false)
  })

  it('passes the instruction-branding validator, which reds a known-bad generated document', async () => {
    const validator = await import(
      /* @vite-ignore */ pathToFileURL(join(repoRoot, 'scripts', 'validate-agent-instructions.mjs')).href
    ) as { validateGeneratedInstructions(documents: readonly { label: string; body: string }[]): string[] }
    const documents = [
      { label: GUIDE, body: buildKnowledgeAgentGuide() },
      { label: 'root AGENTS.md pointer', body: pointerBlock() },
    ]
    expect(validator.validateGeneratedInstructions(documents)).toEqual([])
    expect(validator.validateGeneratedInstructions([{ label: GUIDE, body: `${documents[0]!.body}AgentQA\n` }]))
      .toEqual([`${GUIDE} contains forbidden branding: AgentQA`])
  })
})

describe('INIT-POINTER-PRINT: init prints the root pointer and writes no root file by default', () => {
  it('prints the pointer as a paste-ready managed block', async () => {
    const dir = tempProject()
    await runInit(dir)

    const body = buildAgentInstructionPointer()
    expect(body.length).toBeGreaterThanOrEqual(5)
    expect(body.length).toBeLessThanOrEqual(9)
    const text = body.join('\n')
    for (const needle of [
      'agent-qa runs list', 'agent-qa runs overview <runId>', 'agent-qa-knowledge/AGENTS.md', 'agent-qa skills',
      '--json', 'agent_qa_*', '.agent-qa/', 'SQLite',
    ]) {
      expect(text, needle).toContain(needle)
    }
    expect(stdout()).toContain(`\n${pointerBlock()}\n`)
  })

  it('leaves existing root instruction files byte-identical and creates none', async () => {
    const withFiles = tempProject()
    const agents = '# My agents\n\nkeep me\r\nno final newline'
    const claude = '# Claude\n<!-- agent-qa init:start -->\n'
    writeFileSync(join(withFiles, 'AGENTS.md'), agents)
    writeFileSync(join(withFiles, 'CLAUDE.md'), claude)
    await runInit(withFiles)
    expect(readFileSync(join(withFiles, 'AGENTS.md'), 'utf8')).toBe(agents)
    expect(readFileSync(join(withFiles, 'CLAUDE.md'), 'utf8')).toBe(claude)

    const empty = tempProject()
    await runInit(empty)
    expect(existsSync(join(empty, 'AGENTS.md'))).toBe(false)
    expect(existsSync(join(empty, 'CLAUDE.md'))).toBe(false)
  })

  it('registers the opt-in flag as the init row of the capability manifest', () => {
    expect(INIT_AGENT_INSTRUCTIONS_VERB).toEqual({ verb: 'init', flags: [WRITE_AGENT_INSTRUCTIONS_FLAG] })
    expect(WRITE_AGENT_INSTRUCTIONS_FLAG).toBe('--write-agent-instructions')
  })
})
