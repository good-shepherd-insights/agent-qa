import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const snapshotPath = join(here, 'models.dev.snapshot.json')
const outputPath = join(here, 'family-table.generated.ts')

const providerOverlay = {
  anthropic: { visionToolMessages: true },
}

function numberOrFallback(value, fallback) {
  return Number.isFinite(Number(value)) ? Number(value) : fallback
}

function inferProvider(providerId) {
  return String(providerId ?? '').toLowerCase()
}

function toCapabilityEntry(providerId, modelId, model) {
  const provider = inferProvider(providerId)
  const modalities = model?.modalities?.input ?? []
  const vision = Array.isArray(modalities)
    ? modalities.includes('image') || model?.attachment === true
    : model?.attachment === true
  const overlay = providerOverlay[provider] ?? { visionToolMessages: false }

  return {
    id: `${provider}:${modelId}`,
    caps: {
      text: true,
      vision,
      visionToolMessages: overlay.visionToolMessages,
      toolCalling: model?.tool_call !== false,
      structuredOutput: true,
      streaming: true,
      contextWindow: numberOrFallback(model?.limit?.context, 8192),
      maxOutput: numberOrFallback(model?.limit?.output, 4096),
    },
  }
}

async function loadModelsDev() {
  if (existsSync(snapshotPath)) {
    return JSON.parse(readFileSync(snapshotPath, 'utf8'))
  }

  if (typeof fetch !== 'function') {
    throw new Error('No local models.dev snapshot and global fetch is unavailable')
  }

  const response = await fetch('https://models.dev/api.json')
  if (!response.ok) {
    throw new Error(`models.dev request failed: ${response.status} ${response.statusText}`)
  }
  return response.json()
}

function flattenModels(data) {
  const entries = []
  for (const [providerId, provider] of Object.entries(data)) {
    const models = provider?.models ?? provider
    for (const [modelId, model] of Object.entries(models ?? {})) {
      entries.push(toCapabilityEntry(providerId, modelId, model))
    }
  }
  return entries.sort((a, b) => a.id.localeCompare(b.id))
}

const data = await loadModelsDev()
const entries = flattenModels(data)
const body = `// Generated by scripts/gen-capability-table.mjs. Diff against src/capability/family-table.ts before hand-curating.
export const GENERATED_MODEL_CAPABILITIES = ${JSON.stringify(entries, null, 2)} as const
`

writeFileSync(outputPath, body)
console.log(`Processed ${entries.length} models into ${outputPath}`)
